"""Run the QASeed test suite and save a pytest-html report for a challenge day.

    python scripts/test_report.py            # day worked out from today's date
    python scripts/test_report.py --day 3    # explicit day
    python scripts/test_report.py --day 3 -- -k planner   # extra pytest args after --

Writes reports/day<N>/day<N>_test_report_<YYYYMMDD-HHMMSS>.html (self-contained)
and appends one summary row to reports/day<N>/index.md.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
CHALLENGE_DAY_1 = date(2026, 11, 7)  # Day 3 = Mon 9 Nov 2026 ... Day 8 = Sat 14 Nov 2026
CHALLENGE_DAYS = range(1, 9)


def challenge_day(today: date) -> int | None:
    day = (today - CHALLENGE_DAY_1).days + 1
    return day if day in CHALLENGE_DAYS else None


class _Counts:
    """Collects pass/fail counts from the run for the day index."""

    def __init__(self) -> None:
        self.counts: dict[str, int] = {}

    def pytest_terminal_summary(self, terminalreporter):
        for key in ("passed", "failed", "skipped", "error", "xfailed", "xpassed"):
            self.counts[key] = len(terminalreporter.stats.get(key, []))


def _commit() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True, timeout=10)
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return out.stdout.strip() + ("+uncommitted" if dirty.stdout.strip() else "")


def _append_index(day_dir: Path, day: int, stamp: datetime, report: Path, exit_code: int, counts: dict[str, int]) -> Path:
    index = day_dir / "index.md"
    if not index.exists():
        index.write_text(
            f"# Day {day} — Test Reports\n\n"
            "Generated by `python scripts/test_report.py`. Offline tests only (mock LLM replies).\n\n"
            "| Run (local time) | Result | Passed | Failed | Errors | Skipped | Commit | Report |\n"
            "|---|---|---|---|---|---|---|---|\n",
            encoding="utf-8",
        )
    result = "PASS" if exit_code == 0 else f"FAIL (exit {exit_code})"
    row = (
        f"| {stamp:%Y-%m-%d %H:%M:%S} | {result} | {counts.get('passed', 0)} | {counts.get('failed', 0)} | "
        f"{counts.get('error', 0)} | {counts.get('skipped', 0)} | `{_commit()}` | [{report.name}]({report.name}) |\n"
    )
    with index.open("a", encoding="utf-8") as handle:
        handle.write(row)
    return index


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    extra: list[str] = []
    if "--" in argv:
        split = argv.index("--")
        argv, extra = argv[:split], argv[split + 1:]
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--day", type=int, choices=list(CHALLENGE_DAYS), help="challenge day (1-8)")
    args = parser.parse_args(argv)

    day = args.day or challenge_day(date.today())
    if day is None:
        print("Today is outside the challenge dates (7-14 Nov 2026). Pass --day N.")
        return 2

    stamp = datetime.now()
    day_dir = REPORTS / f"day{day}"
    day_dir.mkdir(parents=True, exist_ok=True)
    report = day_dir / f"day{day}_test_report_{stamp:%Y%m%d-%H%M%S}.html"

    os.environ["QASEED_REPORT_DAY"] = str(day)
    os.chdir(ROOT)
    if str(ROOT) not in sys.path:  # same import behaviour as `python -m pytest` from the project root
        sys.path.insert(0, str(ROOT))
    counts = _Counts()
    exit_code = int(pytest.main(["-q", f"--html={report}", "--self-contained-html", *extra], plugins=[counts]))
    index = _append_index(day_dir, day, stamp, report, exit_code, counts.counts)

    print(f"\nreport={report.relative_to(ROOT)}")
    print(f"index={index.relative_to(ROOT)}")
    print(f"result={'PASS' if exit_code == 0 else 'FAIL'} exit={exit_code}")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
